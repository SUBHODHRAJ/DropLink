using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading.Tasks;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using UglyToad.PdfPig;

namespace DropLink.Api.Services
{
    public class PdfService : IPdfService
    {
        public Task<byte[]> GeneratePdfFromDocumentAsync(string title, string contentHtml, string? plainText = null)
        {
            // Parse plain text or stripped HTML into lines/paragraphs
            var textToRender = !string.IsNullOrWhiteSpace(plainText) 
                ? plainText 
                : StripHtml(contentHtml);

            var paragraphs = textToRender.Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.None);

            var document = QuestPDF.Fluent.Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(40);
                    page.PageColor(Colors.White);
                    page.DefaultTextStyle(x => x.FontSize(11).FontColor(Colors.Grey.Darken3).FontFamily("Lato"));

                    page.Header()
                        .PaddingBottom(15)
                        .Row(row =>
                        {
                            row.RelativeItem().Column(col =>
                            {
                                col.Item().Text(title).FontSize(20).Bold().FontColor(Colors.Blue.Darken2);
                                col.Item().Text($"Generated by DropLink • {DateTime.UtcNow:MMMM dd, yyyy}").FontSize(9).FontColor(Colors.Grey.Medium);
                            });
                        });

                    page.Content()
                        .PaddingVertical(10)
                        .Column(column =>
                        {
                            foreach (var p in paragraphs)
                            {
                                var trimmed = p.Trim();
                                if (string.IsNullOrWhiteSpace(trimmed))
                                {
                                    column.Item().PaddingBottom(8);
                                    continue;
                                }

                                if (trimmed.StartsWith("# ") || (trimmed.Length < 60 && trimmed.EndsWith(":") && !trimmed.Contains(" ")))
                                {
                                    column.Item().PaddingTop(10).PaddingBottom(4).Text(trimmed.TrimStart('#', ' ')).FontSize(15).Bold().FontColor(Colors.Blue.Darken1);
                                }
                                else if (trimmed.StartsWith("## "))
                                {
                                    column.Item().PaddingTop(8).PaddingBottom(3).Text(trimmed.TrimStart('#', ' ')).FontSize(13).SemiBold().FontColor(Colors.Grey.Darken3);
                                }
                                else if (trimmed.StartsWith("- ") || trimmed.StartsWith("* "))
                                {
                                    column.Item().PaddingLeft(15).PaddingBottom(4).Row(r =>
                                    {
                                        r.AutoItem().Text("• ").Bold().FontColor(Colors.Blue.Medium);
                                        r.RelativeItem().Text(trimmed.Substring(2));
                                    });
                                }
                                else
                                {
                                    column.Item().PaddingBottom(6).Text(trimmed).LineHeight(1.4f);
                                }
                            }
                        });

                    page.Footer()
                        .AlignCenter()
                        .Text(x =>
                        {
                            x.Span("Page ");
                            x.CurrentPageNumber();
                            x.Span(" of ");
                            x.TotalPages();
                        });
                });
            });

            var pdfBytes = document.GeneratePdf();
            return Task.FromResult(pdfBytes);
        }

        public Task<byte[]> GeneratePdfFromImagesAsync(List<string> imagePaths, string title)
        {
            var document = QuestPDF.Fluent.Document.Create(container =>
            {
                foreach (var imgPath in imagePaths)
                {
                    if (!File.Exists(imgPath)) continue;

                    container.Page(page =>
                    {
                        page.Size(PageSizes.A4);
                        page.Margin(20);
                        page.PageColor(Colors.White);

                        page.Header().PaddingBottom(10).Text(title).FontSize(12).FontColor(Colors.Grey.Darken1);
                        page.Content().AlignCenter().AlignMiddle().Image(imgPath, ImageScaling.FitArea);
                        page.Footer().AlignCenter().Text(x => { x.CurrentPageNumber(); });
                    });
                }
            });

            return Task.FromResult(document.GeneratePdf());
        }

        public (string ExtractedText, int PageCount, Dictionary<string, string> Metadata) ExtractTextAndMetadata(string pdfFilePath)
        {
            var sb = new StringBuilder();
            var metadata = new Dictionary<string, string>();
            int pageCount = 0;

            if (!File.Exists(pdfFilePath))
            {
                return (string.Empty, 0, metadata);
            }

            try
            {
                using var document = UglyToad.PdfPig.PdfDocument.Open(pdfFilePath);
                pageCount = document.NumberOfPages;

                if (document.Information != null)
                {
                    if (!string.IsNullOrEmpty(document.Information.Title)) metadata["Title"] = document.Information.Title;
                    if (!string.IsNullOrEmpty(document.Information.Author)) metadata["Author"] = document.Information.Author;
                    if (!string.IsNullOrEmpty(document.Information.Subject)) metadata["Subject"] = document.Information.Subject;
                    if (!string.IsNullOrEmpty(document.Information.Keywords)) metadata["Keywords"] = document.Information.Keywords;
                }

                foreach (var page in document.GetPages())
                {
                    var text = page.Text;
                    if (!string.IsNullOrWhiteSpace(text))
                    {
                        sb.AppendLine($"--- Page {page.Number} ---");
                        sb.AppendLine(text);
                    }
                }
            }
            catch (Exception ex)
            {
                sb.AppendLine($"[Extraction Notice: Document read completed with note: {ex.Message}]");
            }

            return (sb.ToString(), pageCount, metadata);
        }

        public Task<byte[]> MergePdfsAsync(List<string> pdfFilePaths)
        {
            // QuestPDF document-level or direct byte merge
            // For merging arbitrary existing PDFs, we can extract pages using PdfPig or stream
            var combinedDocument = QuestPDF.Fluent.Document.Create(container =>
            {
                foreach (var filePath in pdfFilePaths)
                {
                    if (!File.Exists(filePath)) continue;
                    var (text, count, _) = ExtractTextAndMetadata(filePath);

                    container.Page(page =>
                    {
                        page.Size(PageSizes.A4);
                        page.Margin(30);
                        page.Header().Text($"Merged: {Path.GetFileName(filePath)}").FontSize(10).FontColor(Colors.Grey.Medium);
                        page.Content().Text(text.Length > 2000 ? text.Substring(0, 2000) + "..." : text);
                        page.Footer().AlignCenter().Text(x => x.CurrentPageNumber());
                    });
                }
            });

            return Task.FromResult(combinedDocument.GeneratePdf());
        }

        private static string StripHtml(string input)
        {
            if (string.IsNullOrEmpty(input)) return string.Empty;
            // Replace <br> and <p> with newlines
            var formatted = Regex.Replace(input, @"<(br|p|\/p)[^>]*>", "\n", RegexOptions.IgnoreCase);
            // Remove remaining HTML tags
            var stripped = Regex.Replace(formatted, @"<[^>]*>", " ", RegexOptions.IgnoreCase);
            return System.Net.WebUtility.HtmlDecode(stripped).Trim();
        }
    }
}
